function overallRank(playerName){const idx=(allData.Overall||[]).findIndex(p=>normalizeName(p.name)===normalizeName(playerName));return idx>=0?idx+1:1}
function categoryScoreForPlayer(playerName, category){
  const keys = CATEGORY_META[category].modes.filter(k=>k!=="Overall");
  const result = {score:0, tested:0, exactTiers:[]};
  keys.forEach(key=>{
    const tier = getTier(playerName, key);
    if (tier && tier !== '-') {
      result.score += TIER_SCORE[tier] || 0;
      result.tested += 1;
      result.exactTiers.push(tier);
    }
  });
  return result;
}
function categoryRanking(category){
  const keys = CATEGORY_META[category].modes.filter(k=>k!=="Overall");
  const pool = new Map();
  keys.forEach(key=>{
    (allData[modeDataKey(key)] || []).forEach(p=>{
      const n = normalizeName(p.name);
      if (!pool.has(n)) pool.set(n, { name: p.name });
    });
  });
  const ranked = [...pool.values()].map(p=>{
    const agg = categoryScoreForPlayer(p.name, category);
    return {
      name: p.name,
      score: agg.score,
      tested: agg.tested,
      pts: overallPoints(p.name)
    };
  }).sort((a,b)=> b.score-a.score || b.tested-a.tested || b.pts-a.pts || a.name.localeCompare(b.name));
  return ranked;
}
